// SnippetInfo 描述一个片段。
type SnippetInfo struct {
	Name    string `json:"name"`
	Source  string `json:"source"`
	Builtin bool   `json:"builtin"`
}

// ShellInitResult 是 `bs shell init` 的结果。
type ShellInitResult struct {
	Shell    string        `json:"shell"`
	Family   string        `json:"family"`
	Snippets []SnippetInfo `json:"snippets"`
	Content  string        `json:"content"`
}

// ShellInit 渲染某个 shell 的受管内容（包装函数 + 片段 + PATH/代理装配）。
func (a *App) ShellInit(shell string) (ShellInitResult, error) {
	family, err := shellsnip.FamilyForShell(shell)
	if err != nil {
		return ShellInitResult{}, err
	}
	set, err := shellsnip.Load(tools.Snippets, family, a.Cfg.Shell.SnippetsDir)
	if err != nil {
		return ShellInitResult{}, err
	}
	set.Snippets, err = a.applyShellOptions(family, set.Snippets)
	if err != nil {
		return ShellInitResult{}, err
	}
	infos := make([]SnippetInfo, 0, len(set.Snippets))
	for _, s := range set.Snippets {
		infos = append(infos, SnippetInfo{Name: s.Name, Source: s.Source, Builtin: s.Builtin})
	}
	header := fmt.Sprintf("# ── generated by `bs shell init %s` ── 片段改动请改 %s 或仓库 tools/snippets/\n",
		shell, a.Cfg.Shell.SnippetsDir)
	if !a.Cfg.Shell.AutoPath {
		header += "# 注意：shell.auto_path=false，已省略 PATH 装配片段（20-path）\n"
	}
	return ShellInitResult{
		Shell:    shell,
		Family:   string(family),
		Snippets: infos,
		Content:  header + set.Render(),
	}, nil
}

// applyShellOptions 按配置调整要渲染的片段：
//   - `shell.auto_path=false` → 去掉 PATH 装配片段（20-path）；
//   - `shell.auto_proxy=true` → 追加"启动时自动应用代理"片段（默认关，见配置说明）。
//
// 放在渲染阶段而不是写受管块阶段：受管块只有一行 `eval "$(bs shell init <shell>)"`，
// 真正的内容每次开 shell 时现算，改配置后无需重写 rc 文件即可生效。
func (a *App) applyShellOptions(family shellsnip.Family, snippets []shellsnip.Snippet) ([]shellsnip.Snippet, error) {
	out := make([]shellsnip.Snippet, 0, len(snippets)+1)
	for _, sn := range snippets {
		if !a.Cfg.Shell.AutoPath && shellsnip.IsPathSnippet(sn.Name) {
			continue
		}
		out = append(out, sn)
	}
	if a.Cfg.Shell.AutoProxy {
		content, err := shellsnip.AutoProxyContent(family)
		if err != nil {
			return nil, err
		}
		out = append(out, shellsnip.Snippet{
			Name:    "99-auto-proxy",
			Family:  family,
			Builtin: true,
			Content: content,
		})
	}
	return out, nil
}

// ResolveRCFile 确定目标 rc 文件：显式指定 > 配置 > 自动探测。
func (a *App) ResolveRCFile(shell, explicit string) (string, error) {
	if explicit != "" {
		return fsx.ExpandPath(explicit, a.Paths.HomeDir), nil
	}
	if a.Cfg.Shell.RCFiles != nil {
		if f, ok := a.Cfg.Shell.RCFiles[normalizeShellKey(shell)]; ok && f != "" {
			return f, nil
		}
	}
	return shellsnip.DetectRCFile(a.Platform.OS, shell, a.Paths.HomeDir, getenv, fsx.IsFile)
}

func normalizeShellKey(shell string) string {
	switch strings.ToLower(strings.TrimSpace(shell)) {
	case "sh", "dash", "ksh":
		return "bash"
	case "powershell", "powershell.exe":
		return "pwsh"
	default:
		return strings.ToLower(strings.TrimSpace(shell))
	}
}

// ShellInstallResult 是 `bs shell install` 的结果。
type ShellInstallResult struct {
	Shell      string `json:"shell"`
	RCFile     string `json:"rc_file"`
	Changed    bool   `json:"changed"`
	Backup     string `json:"backup,omitempty"`
	Block      string `json:"block"`
	DryRunDiff string `json:"diff,omitempty"`
}

// ShellInstall 幂等写入受管块。dry-run 时不触碰任何文件。
func (a *App) ShellInstall(shell, rcFile string) (ShellInstallResult, error) {
	rc, err := a.ResolveRCFile(shell, rcFile)
	if err != nil {
		return ShellInstallResult{}, err
	}
	block, err := shellsnip.Block(shell)
	if err != nil {
		return ShellInstallResult{}, err
	}

	var existing string
	if data, err := os.ReadFile(rc); err == nil {
		existing = string(data)
	} else if !os.IsNotExist(err) {
		return ShellInstallResult{}, fmt.Errorf("read %s: %w", rc, err)
	}

	updated, changed := shellsnip.Upsert(existing, block)
	result := ShellInstallResult{Shell: shell, RCFile: rc, Changed: changed, Block: block}
	if !changed {
		return result, nil
	}
	if a.DryRun {
		result.DryRunDiff = diffSummary(existing, updated)
		a.Log.Info("dry-run: would update rc file", "file", rc)
		return result, nil
	}

	if fsx.IsFile(rc) {
		backup, err := fsx.BackupFile(rc, Stamp())
		if err != nil {
			return result, err
		}
		result.Backup = backup
	}
	if err := fsx.AtomicWriteFile(rc, []byte(updated), 0o644); err != nil {
		return result, err
	}
	return result, nil
}

// ShellUninstallResult 是 `bs shell uninstall` 的结果。
type ShellUninstallResult struct {
	Shell   string `json:"shell"`
	RCFile  string `json:"rc_file"`
	Removed bool   `json:"removed"`
	Backup  string `json:"backup,omitempty"`
}

// ShellUninstall 精确移除受管块，块外内容不变。
func (a *App) ShellUninstall(shell, rcFile string) (ShellUninstallResult, error) {
	rc, err := a.ResolveRCFile(shell, rcFile)
	if err != nil {
		return ShellUninstallResult{}, err
	}
	result := ShellUninstallResult{Shell: shell, RCFile: rc}
	data, err := os.ReadFile(rc)
	if os.IsNotExist(err) {
		return result, nil
	}
	if err != nil {
		return result, fmt.Errorf("read %s: %w", rc, err)
	}
	updated, removed := shellsnip.Remove(string(data))
	if !removed {
		return result, nil
	}
	result.Removed = true
	if a.DryRun {
		a.Log.Info("dry-run: would remove managed block", "file", rc)
		return result, nil
	}
	backup, err := fsx.BackupFile(rc, Stamp())
	if err != nil {
		return result, err
	}
	result.Backup = backup
	if err := fsx.AtomicWriteFile(rc, []byte(updated), 0o644); err != nil {
		return result, err
	}
	return result, nil
}

// ShellStatus 报告受管块状态。
type ShellStatus struct {
	Shell     string `json:"shell"`
	RCFile    string `json:"rc_file"`
	RCExists  bool   `json:"rc_exists"`
	HasBlock  bool   `json:"has_block"`
	UpToDate  bool   `json:"up_to_date"`
	Expected  string `json:"expected"`
	Actual    string `json:"actual,omitempty"`
	Snippets  int    `json:"snippets"`
	SnippetOK bool   `json:"snippets_ok"`
}

// ShellStatusOf 计算受管块与当前版本的差异。
func (a *App) ShellStatusOf(shell, rcFile string) (ShellStatus, error) {
	rc, err := a.ResolveRCFile(shell, rcFile)
	if err != nil {
		return ShellStatus{}, err
	}
	block, err := shellsnip.Block(shell)
	if err != nil {
		return ShellStatus{}, err
	}
	init, err := a.ShellInit(shell)
	if err != nil {
		return ShellStatus{}, err
	}
	st := ShellStatus{
		Shell:     shell,
		RCFile:    rc,
		Expected:  block,
		Snippets:  len(init.Snippets),
		SnippetOK: len(init.Snippets) > 0,
	}
	data, err := os.ReadFile(rc)
	if os.IsNotExist(err) {
		return st, nil
	}
	if err != nil {
		return st, fmt.Errorf("read %s: %w", rc, err)
	}
	st.RCExists = true
	content := string(data)
	st.HasBlock = shellsnip.HasBlock(content)
	if st.HasBlock {
		updated, changed := shellsnip.Upsert(content, block)
		st.UpToDate = !changed && updated == content
		if begin := strings.Index(content, shellsnip.BeginMarker); begin >= 0 {
			if rel := strings.Index(content[begin:], shellsnip.EndMarker); rel >= 0 {
				st.Actual = content[begin : begin+rel+len(shellsnip.EndMarker)]
			}
		}
	}
	return st, nil
}

// ShellSnippets 列出某个 shell 家族合并后的片段。
func (a *App) ShellSnippets(shell string) ([]SnippetInfo, string, error) {
	family, err := shellsnip.FamilyForShell(shell)
	if err != nil {
		return nil, "", err
	}
	set, err := shellsnip.Load(tools.Snippets, family, a.Cfg.Shell.SnippetsDir)
	if err != nil {
		return nil, "", err
	}
	out := make([]SnippetInfo, 0, len(set.Snippets))
	for _, s := range set.Snippets {
		out = append(out, SnippetInfo{Name: s.Name, Source: s.Source, Builtin: s.Builtin})
	}
	return out, filepath.Join(a.Cfg.Shell.SnippetsDir, string(family)), nil
}

// SnippetUserDir 返回某个 shell 家族的用户片段目录。
func (a *App) SnippetUserDir(shell string) (string, error) {
	family, err := shellsnip.FamilyForShell(shell)
	if err != nil {
		return "", err
	}
	return filepath.Join(a.Cfg.Shell.SnippetsDir, string(family)), nil
}

// ShellSubshell 打开一个已装配环境的子 shell（不改 rc）。
func (a *App) ShellSubshell(ctx context.Context, shell string, profileName string) (int, error) {
	if shell == "" {
		shell = a.Platform.Shell
	}
	if shell == "" {
		shell = "bash"
	}
	init, err := a.ShellInit(shell)
	if err != nil {
		return 1, err
	}
	script := init.Content
	if profileName != "" {
		env, err := a.RenderProxyEnv(profileName, false, shell)
		if err != nil {
			return 1, err
		}
		script = env + "\n" + script
	}
	return a.runInteractiveShell(ctx, shell, script)
}

func diffSummary(before, after string) string {
	if before == after {
		return ""
	}
	beforeLines := strings.Count(before, "\n")
	afterLines := strings.Count(after, "\n")
	return fmt.Sprintf("rc 行数 %d -> %d", beforeLines, afterLines)
}
